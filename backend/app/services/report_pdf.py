from datetime import datetime, timezone
from typing import Any, Dict, List

from fpdf import FPDF
from fpdf.enums import XPos, YPos


def _safe_text(val: Any) -> str:
    text = str(val if val is not None else "")
    replacements = {
        "\u2013": "-",
        "\u2014": "--",
        "\u2026": "...",
        "\u2018": "'",
        "\u2019": "'",
        "\u201c": '"',
        "\u201d": '"',
        "\u00b7": "|",
    }
    for k, v in replacements.items():
        text = text.replace(k, v)
    return text.encode("latin-1", "replace").decode("latin-1")


class SurveyOpsPDF(FPDF):
    def __init__(self, report_title: str, survey_code: str):
        super().__init__()
        self.report_title = _safe_text(report_title)
        self.survey_code = _safe_text(survey_code)
        self.set_auto_page_break(auto=True, margin=18)

    def header(self):
        self.set_fill_color(15, 30, 54)
        self.rect(0, 0, 210, 18, "F")
        self.set_text_color(255, 255, 255)
        self.set_font("Helvetica", "B", 11)
        self.set_xy(14, 5)
        self.cell(120, 8, "SURVEYOPS  |  FIELD SURVEY INTELLIGENCE REPORT")
        self.set_font("Helvetica", "", 9)
        self.set_xy(135, 5)
        self.cell(61, 8, f"Survey: {self.survey_code}", align="R")
        self.ln(18)

    def footer(self):
        self.set_y(-14)
        self.set_draw_color(226, 228, 233)
        self.line(14, self.get_y(), 196, self.get_y())
        self.set_font("Helvetica", "", 8)
        self.set_text_color(100, 116, 139)
        ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
        self.cell(120, 8, f"Generated by SurveyOps Enterprise Analytics  |  {ts}")
        self.cell(0, 8, f"Page {self.page_no()}/{{nb}}", align="R")


def render_insight_report_pdf(
    report_title: str,
    survey_title: str,
    survey_code: str,
    survey_category: str,
    author_name: str,
    created_at: str,
    summary_stats: Dict[str, Any],
    quality_summary: Dict[str, Any],
    geo_summary: List[Dict[str, Any]],
    question_insights: List[Dict[str, Any]],
    analyst_notes: str,
) -> bytes:
    pdf = SurveyOpsPDF(report_title=report_title, survey_code=survey_code)
    pdf.alias_nb_pages()
    pdf.add_page()

    # Title Block
    pdf.set_text_color(15, 30, 54)
    pdf.set_font("Helvetica", "B", 16)
    pdf.multi_cell(0, 8, _safe_text(report_title))
    pdf.ln(1)

    pdf.set_font("Helvetica", "", 9.5)
    pdf.set_text_color(66, 82, 107)
    pdf.cell(
        0,
        5,
        _safe_text(f"Survey: {survey_title} ({survey_code})  |  Category: {survey_category}"),
        new_x=XPos.LMARGIN,
        new_y=YPos.NEXT,
    )
    pdf.cell(
        0,
        5,
        _safe_text(f"Prepared by: {author_name}  |  Snapshot Date: {created_at[:19].replace('T', ' ')} UTC"),
        new_x=XPos.LMARGIN,
        new_y=YPos.NEXT,
    )
    pdf.ln(4)

    # Section 1: Response Statistics Grid
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(15, 118, 110)
    pdf.cell(0, 7, "1. EXECUTIVE RESPONSE SUMMARY", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.set_draw_color(226, 228, 233)
    pdf.line(14, pdf.get_y(), 196, pdf.get_y())
    pdf.ln(3)

    kpis = [
        ("Total Collected", f"{summary_stats.get('total_responses', 0):,}"),
        ("Approved & Valid", f"{summary_stats.get('valid_responses', 0):,} ({summary_stats.get('valid_rate', 0)}%)"),
        ("Flagged / Rejected", f"{summary_stats.get('flagged_responses', 0):,} / {summary_stats.get('rejected_responses', 0):,}"),
        ("Avg Quality Score", f"{summary_stats.get('avg_quality_score', 0)} / 100"),
        ("Target Completion", f"{summary_stats.get('completion_rate', 0)}%"),
        ("Avg Duration", f"{summary_stats.get('avg_duration_seconds', 0)}s"),
    ]

    col_w = 60
    start_x = 14
    for i, (label, value) in enumerate(kpis):
        col = i % 3
        if col == 0 and i > 0:
            pdf.ln(15)
        x = start_x + col * (col_w + 1)
        y = pdf.get_y()
        pdf.set_fill_color(246, 246, 244)
        pdf.set_draw_color(226, 228, 233)
        pdf.rect(x, y, col_w - 2, 13, "DF")
        pdf.set_xy(x + 3, y + 2)
        pdf.set_font("Helvetica", "", 7.5)
        pdf.set_text_color(100, 116, 139)
        pdf.cell(col_w - 8, 4, _safe_text(label.upper()))
        pdf.set_xy(x + 3, y + 6.5)
        pdf.set_font("Helvetica", "B", 10.5)
        pdf.set_text_color(15, 30, 54)
        pdf.cell(col_w - 8, 5, _safe_text(value))
    pdf.ln(18)

    # Section 2: Analyst Notes
    if analyst_notes and analyst_notes.strip():
        pdf.set_font("Helvetica", "B", 11)
        pdf.set_text_color(15, 118, 110)
        pdf.cell(0, 7, "2. ANALYST FINDINGS & COMMENTARY", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.set_draw_color(226, 228, 233)
        pdf.line(14, pdf.get_y(), 196, pdf.get_y())
        pdf.ln(3)
        pdf.set_font("Helvetica", "", 9.5)
        pdf.set_text_color(15, 30, 54)
        pdf.multi_cell(0, 5.2, _safe_text(analyst_notes.strip()))
        pdf.ln(4)

    # Section 3: Data Quality Summary
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(15, 118, 110)
    pdf.cell(0, 7, "3. DATA QUALITY & PIPELINE AUDIT SUMMARY", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.set_draw_color(226, 228, 233)
    pdf.line(14, pdf.get_y(), 196, pdf.get_y())
    pdf.ln(3)

    by_type = quality_summary.get("by_type", [])
    if by_type:
        pdf.set_fill_color(240, 239, 233)
        pdf.set_text_color(15, 30, 54)
        pdf.set_font("Helvetica", "B", 8.5)
        pdf.cell(62, 6.5, "Issue Category", border=1, fill=True)
        pdf.cell(30, 6.5, "Total", border=1, align="R", fill=True)
        pdf.cell(30, 6.5, "Open", border=1, align="R", fill=True)
        pdf.cell(30, 6.5, "Resolved", border=1, align="R", fill=True)
        pdf.cell(30, 6.5, "Dismissed", border=1, align="R", fill=True, new_x=XPos.LMARGIN, new_y=YPos.NEXT)

        pdf.set_font("Helvetica", "", 8.5)
        for item in by_type:
            pdf.cell(62, 6, _safe_text(item.get("issue_type", "").replace("_", " ").title()), border=1)
            pdf.cell(30, 6, f"{item.get('total', 0):,}", border=1, align="R")
            pdf.cell(30, 6, f"{item.get('open', 0):,}", border=1, align="R")
            pdf.cell(30, 6, f"{item.get('resolved', 0):,}", border=1, align="R")
            pdf.cell(30, 6, f"{item.get('dismissed', 0):,}", border=1, align="R", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    else:
        pdf.set_font("Helvetica", "", 9)
        pdf.set_text_color(66, 82, 107)
        pdf.cell(0, 6, "No data quality anomalies detected in the selected scope.", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.ln(5)

    # Section 4: Geographic Distribution
    if geo_summary:
        pdf.set_font("Helvetica", "B", 11)
        pdf.set_text_color(15, 118, 110)
        pdf.cell(0, 7, "4. GEOGRAPHIC RESPONSE DISTRIBUTION", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.set_draw_color(226, 228, 233)
        pdf.line(14, pdf.get_y(), 196, pdf.get_y())
        pdf.ln(3)

        pdf.set_fill_color(240, 239, 233)
        pdf.set_text_color(15, 30, 54)
        pdf.set_font("Helvetica", "B", 8.5)
        pdf.cell(52, 6.5, "District / Zone", border=1, fill=True)
        pdf.cell(26, 6.5, "Total", border=1, align="R", fill=True)
        pdf.cell(26, 6.5, "Valid", border=1, align="R", fill=True)
        pdf.cell(26, 6.5, "Valid %", border=1, align="R", fill=True)
        pdf.cell(26, 6.5, "Avg Score", border=1, align="R", fill=True)
        pdf.cell(26, 6.5, "GPS Consent", border=1, align="R", fill=True, new_x=XPos.LMARGIN, new_y=YPos.NEXT)

        pdf.set_font("Helvetica", "", 8.5)
        for g in geo_summary[:12]:
            pdf.cell(52, 6, _safe_text(g.get("district", "")), border=1)
            pdf.cell(26, 6, f"{g.get('total', 0):,}", border=1, align="R")
            pdf.cell(26, 6, f"{g.get('valid', 0):,}", border=1, align="R")
            pdf.cell(26, 6, f"{g.get('valid_rate', 0)}%", border=1, align="R")
            pdf.cell(26, 6, str(g.get("avg_quality_score", 0)), border=1, align="R")
            pdf.cell(26, 6, f"{g.get('gps_coverage_pct', 0)}%", border=1, align="R", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.ln(5)

    # Section 5: Question-Level Insights
    if question_insights:
        pdf.set_font("Helvetica", "B", 11)
        pdf.set_text_color(15, 118, 110)
        pdf.cell(0, 7, "5. QUESTION-LEVEL DISTRIBUTIONS & INSIGHTS", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.set_draw_color(226, 228, 233)
        pdf.line(14, pdf.get_y(), 196, pdf.get_y())
        pdf.ln(3)

        for idx, qi in enumerate(question_insights, start=1):
            if pdf.get_y() > 245:
                pdf.add_page()
            pdf.set_font("Helvetica", "B", 9.5)
            pdf.set_text_color(15, 30, 54)
            pdf.multi_cell(0, 5, _safe_text(f"Q{idx}. [{qi.get('question_key')}] {qi.get('prompt')}"))
            pdf.set_font("Helvetica", "", 8)
            pdf.set_text_color(100, 116, 139)
            meta = f"Type: {qi.get('question_type')}  |  Answered: {qi.get('answered_count', 0):,} ({qi.get('response_rate', 0)}%)  |  Outliers: {qi.get('outlier_count', 0):,}"
            if qi.get("numeric_stats"):
                ns = qi["numeric_stats"]
                meta += f"  |  Mean: {ns.get('mean')} (Min: {ns.get('min')}, Max: {ns.get('max')})"
            pdf.cell(0, 4.5, _safe_text(meta), new_x=XPos.LMARGIN, new_y=YPos.NEXT)

            dist = qi.get("distribution", [])[:6]
            if dist:
                pdf.set_font("Helvetica", "", 8.5)
                pdf.set_text_color(15, 30, 54)
                for row in dist:
                    label = _safe_text(row.get("label", ""))[:58]
                    pct = float(row.get("pct", 0))
                    bar_w = max(1, int(pct * 0.45))
                    y = pdf.get_y()
                    pdf.cell(88, 5, f"  - {label}")
                    pdf.set_fill_color(15, 118, 110)
                    pdf.rect(105, y + 1.2, bar_w, 2.8, "F")
                    pdf.set_xy(155, y)
                    pdf.cell(41, 5, f"{row.get('count', 0):,} ({pct}%)", align="R", new_x=XPos.LMARGIN, new_y=YPos.NEXT)
            pdf.ln(3)

    return bytes(pdf.output())
